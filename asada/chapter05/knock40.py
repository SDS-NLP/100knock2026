import os

from dotenv import load_dotenv
from google import genai

load_dotenv()
API_KEY = os.getenv("GEMINI_API_KEY")
client = genai.Client(api_key=API_KEY)

contents = """
9世紀に活躍した人物に関係するできごとについて述べた次のア～ウを年代の古い順に正しく並べよ。

ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。
イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。
ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。
"""
response = client.models.generate_content_stream(
    model="gemini-3.5-flash", contents=contents
)

for chunk in response:
    print(chunk.text, end="", flush=True)

# output
# ご提示いただいたア〜ウのできごとを年代の古い順に並べると、**「イ → ウ → ア」**になります。
#
# それぞれのできごとの年代と詳細な解説は以下の通りです。
#
# * **イ：嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。（810年）**
#   嵯峨天皇と平城上皇の対立から発展した「薬子の変（平城太上天皇の変）」の際、機密保持と迅速な政務処理のために「蔵人所」が設置され、その長官である初代「蔵人頭（くろうどのとう）」に藤原冬嗣（北家）らが任命されました。これにより、冬嗣の属する藤原北家が台頭するきっかけとなりました。
#
# * **ウ：藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。（842年）**
#   仁明天皇の後継者をめぐる政変「承和の変（じょうわのへん）」が起こり、藤原良房（冬嗣の子）が伴健岑（とものこわみね）や橘逸勢（たちばなのはやなり）らを退けました。これにより良房は他氏を排斥するとともに、藤原氏の中でも「北家」の優位を決定づけました。
#
# * **ア：藤原時平は，策謀を用いて菅原道真を政界から追放した。（901年）**
#   宇多天皇に重用されて右大臣にまで昇りつめた菅原道真を、左大臣の藤原時平（良房の従孫）が謀略によって大宰府に左遷した「昌泰の変（しょうたいのへん）」です（道真・時平ともに9世紀後半から活躍した人物です）。
#
# 以上のことから、年代の古い順（時系列）に並べると、**イ → ウ → ア** となります。
