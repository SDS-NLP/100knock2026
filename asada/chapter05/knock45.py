# 3. **目的地（緑が丘駅）までの駅数を数える**
#    二子玉川駅から目的地の「緑が丘駅」までの停車駅は以下の通りです。
#    * 1駅先：上野毛（かみのげ）
#    * 2駅先：等々力（とどろき）
#    * 3駅先：尾山台（おやまだい）
#    * 4駅先：九品仏（くほんぶつ）
#    * 5駅先：自由が丘（じゆうがおか）
#    * **6駅先：緑が丘（みどりがおか）**
#
# したがって、二子玉川駅で各駅停車に乗車した後、**6駅先**の駅で降りれば目的地に到着します。
