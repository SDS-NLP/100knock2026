from gensim.models import KeyedVectors
from sklearn.cluster import KMeans
import numpy as np

file = "data/GoogleNews-vectors-negative300.bin.gz"
model = KeyedVectors.load_word2vec_format(file, binary=True)

analogy_file = "data/questions-words.txt"


def extract_countries(filepath):
    countries = set()
    count = 0

    with open(filepath, encoding="utf-8") as f:
        for line in f:
            line = line.strip()

            if line.startswith(":"):
                continue

            words = line.split()

            for word in words:
                if word in model.key_to_index:
                    countries.add(word)
            count += 1
            if count % 10 == 0:
                print(f"{count}件処理済み")

    return sorted(countries)


countries = extract_countries(analogy_file)

X = np.array([model[word] for word in countries])

kmeans = KMeans(n_clusters=5, random_state=0, n_init=10)

print("kmeans don")

labels = kmeans.fit_predict(X)

for country, label in zip(countries, labels):
    print(label, country)


