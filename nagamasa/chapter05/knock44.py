# つばめちゃんの路線問題（目的地の駅名を答えさせる）への応答を生成する。

client = genai.Client()  # GEMINI_API_KEY を自動で読む
MODEL = "gemini-3.1-flash-lite"  # 最新IDは要確認 / 差し替え可

# --- 与えられた問いかけ（problem.md からそのまま） ---
QUESTION = """\
つばめちゃんは渋谷駅から東急東横線に乗り、自由が丘駅で乗り換えました。東急大井町線の大井町方面の電車に乗り換えたとき、各駅停車に乗車すべきところ、間違えて急行に乗車してしまったことに気付きました。自由が丘の次の急行停車駅で降車し、反対方向の電車で一駅戻った駅がつばめちゃんの目的地でした。目的地の駅の名前を答えてください。"""

# --- QUESTION をそのまま送り、応答を表示（zero-shot, 目視判定） ---
resp = client.models.generate_content(
    model=MODEL,
    contents=QUESTION,
)
print(resp.text)

