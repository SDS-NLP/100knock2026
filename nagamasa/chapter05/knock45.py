from google import genai

# 45. マルチターン対話
# 問44の応答に続けて、追加の問いかけにも答えさせる。
# マルチターン = これまでの発話（user/assistant）を履歴として持ち越して送る。

client = genai.Client()  # GEMINI_API_KEY を自動で読む
MODEL = "gemini-3.1-flash-lite"  # 最新IDは要確認 / 差し替え可

# --- 1ターン目（問44と同じ問いかけ） ---
TURN1 = """\
つばめちゃんは渋谷駅から東急東横線に乗り、自由が丘駅で乗り換えました。東急大井町線の大井町方面の電車に乗り換えたとき、各駅停車に乗車すべきところ、間違えて急行に乗車してしまったことに気付きました。自由が丘の次の急行停車駅で降車し、反対方向の電車で一駅戻った駅がつばめちゃんの目的地でした。目的地の駅の名前を答えてください。"""

# --- 2ターン目（追加の問いかけ） ---
TURN2 = """\
さらに、つばめちゃんが自由が丘駅で乗り換えたとき、先ほどとは反対方向の急行電車に間違って乗車してしまった場合を考えます。目的地の駅に向かうため、自由が丘の次の急行停車駅で降車した後、反対方向の各駅停車に乗車した場合、何駅先の駅で降りれば良いでしょうか？"""

# --- 1ターン目: TURN1 を送って応答を得る ---
resp = client.models.generate_content(
    model=MODEL,
    contents={"role": "user", "parts": [{"text": TURN1}]},
)
print(resp.text)

# --- 2ターン目: [user(TURN1), model(1ターン目の応答), user(TURN2)] を履歴として渡す ---
#     "先ほど" が効くよう、1ターン目の応答を model ロールで履歴に挿してから TURN2 を送る。
resp = client.models.generate_content(
    model=MODEL,
    contents=[
        {"role": "user", "parts": [{"text": TURN1}]},
        {"role": "model", "parts": [{"text": resp.text}]},
        {"role": "user", "parts": [{"text": TURN2}]},
    ],
)
print(resp.text)

