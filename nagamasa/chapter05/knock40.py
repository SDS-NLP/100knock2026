from google import genai

# 40. Zero-Shot推論
# 9世紀の出来事ア〜ウを年代の古い順に並べる問題を zero-shot で解かせる。
# zero-shot = 例（お手本の問答）を一切与えず、本番の問いだけを送る。

client = genai.Client()  # GEMINI_API_KEY を自動で読む
MODEL = "gemini-3.1-flash-lite"  # 最新IDは要確認 / 差し替え可

# --- 与えられた問題文（problem.md からそのまま） ---
QUESTION = """\
9世紀に活躍した人物に関係するできごとについて述べた次のア〜ウを年代の古い順に正しく並べよ。
ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。
イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。
ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。"""

# --- 問いだけを送って（zero-shot）、応答をそのまま表示 ---
resp = client.models.generate_content(
    model=MODEL,
    contents=QUESTION,
)
print(resp.text)

# --- 実行結果（目視判定: イ→ウ→ア で正解。810→842→901年） ---
