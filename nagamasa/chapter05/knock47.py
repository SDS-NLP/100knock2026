from google import genai

# 47. LLMによる評価
# LLM を評価者（ジャッジ）として、問46の川柳の面白さを 10 段階で評価させる。

client = genai.Client()  # GEMINI_API_KEY を自動で読む
MODEL = "gemini-3.1-flash-lite"  # 最新IDは要確認 / 差し替え可

# --- 評価対象（問46で作った川柳。生成結果を貼るか読み込む） ---
QUESTION = """\
あなたは教養深い文化人です。

お題に沿って以下の10句の川柳を1-10の10段階で評価してください。

お題はサラリーマンです。サラリーマンに関するあれこれをうたったものです。俗にいう、サラリーマン川柳。

評価対象の川柳は以下。
---
1:朝の駅　背中合わせる　戦士たち
2:「了解」と　心で毒づく　指示メール
3:また増える　会議の議題　定時過ぎ
4:背広着て　自分殺して　愛想笑い
5:満員で　吊り革守る　我が城よ
6:給料日　通帳見つめ　ため息ひとつ
7:中年の　腹を凹ませ　改札へ
8:飲み会で　上司の昔話　またループ
9:パソコンを　閉じれば始まる　父の顔
10:夢の中　納期に追われ　目が覚める
---

制約：出力形式は以下に沿うこと。それ以外の出力を禁止する。
1:9
2:8
"""
resp = client.models.generate_content(
    model=MODEL,
    contents=QUESTION,
)
print(resp.text)
