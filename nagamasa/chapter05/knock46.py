from google import genai

# 46. 川柳の生成
# 適当なお題を設定し、川柳の案を 10 個作らせる。

client = genai.Client()  # GEMINI_API_KEY を自動で読む
MODEL = "gemini-3.1-flash-lite"  # 最新IDは要確認 / 差し替え可

# --- お題（サラリーマン川柳）を決め、10句を機械分割できる形式で出させる ---
#     出力は「番号:句」（半角コロン, 1行1句）。47/48 で各行を split(":") して句を取り出す。
QUESTION = """\
あなたは教養深いサラリーマンです。

お題に沿って10句の川柳を作成してください。

お題はサラリーマンです。サラリーマンに関するあれこれをうたってください。俗にいう、サラリーマン川柳。

制約：出力形式は以下に沿うこと。それ以外の出力を禁止する。
---
1:１つ目の川柳
2:２つ目の川柳
---
"""

resp = client.models.generate_content(
    model=MODEL,
    contents=QUESTION,
)
print(resp.text)

