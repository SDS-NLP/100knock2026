#大規模言語モデルを評価者（ジャッジ）として、問題46の川柳の面白さを10段階で評価せよ。

from google import genai
import gemini_api

prompt = """
あなたは川柳の専門家です。
「自然言語処理(NLP)」をお題とした以下の10個の川柳について、それぞれ10段階(1〜10)で評価しその理由を簡潔に出力してください。
最後に全体的な評価と感想を出力してください。
1. AIが　文脈読み取り　主語迷う
2. プロンプト　悩み書き込み　答え待つ
3. 壁打ちで　知恵を授かり　夜が明け
4. 誤字一つ　修正求めて　AI泣く
5. 要約を　頼んだはずが　長文に
6. 翻訳の　ニュアンス微妙で　手直しす
7. AIと　対話重ねて　我に返る
8. 感情を　学習させて　君を試す
9. 力の　ハルシネーション　夢の跡
10. 最新の　モデルに乗り換え　君と別れ
"""

client = genai.Client(api_key = gemini_api.api_key)

response = client.models.generate_content(
    model = "gemini-3.1-flash-lite", contents = prompt, config = {"temperature": 0.0}
)

print("回答：")
print(response.text)

#回答：
