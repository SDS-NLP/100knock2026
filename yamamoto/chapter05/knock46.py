#適当なお題を設定し、川柳の案を10個作成せよ。

from google import genai
import gemini_api

prompt = """
自然言語処理(NLP)をお題として、川柳の案を10個作成してください。
その際は思考過程は出力せず、完成した10個の川柳だけを出力してください。
以下は川柳のルールになります。
・五、七、五の十七音で成立(長音、促音、拗音、撥音は1音で数え、上句は七音程度までは許される)
・句のどこかに人間が存在するようにする(今回登場するのは人間でなくてAIやLLMでも構いません)
・何が、何をして、何となる、の形で、自分が経験したあらゆる場面を題材として自分の気持ちを詠む
・川柳を作ったら、ぎこちないところはないか、独りよがりではないか、読み手に伝わるかを推敲する
"""

client = genai.Client(api_key = gemini_api.api_key)

response = client.models.generate_content(
    model = "gemini-3.1-flash-lite", contents = prompt
)

print("回答：")
print(response.text)

