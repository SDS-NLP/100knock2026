#以下の問いかけに対する応答を生成せよ。

from google import genai
import gemini_api

prompt = """
つばめちゃんは渋谷駅から東急東横線に乗り、自由が丘駅で乗り換えました。
東急大井町線の大井町方面の電車に乗り換えたとき、各駅停車に乗車すべきところ、間違えて急行に乗車してしまったことに気付きました。
自由が丘の次の急行停車駅で降車し、反対方向の電車で一駅戻った駅がつばめちゃんの目的地でした。
目的地の駅の名前を答えてください。
"""

client = genai.Client(api_key = gemini_api.api_key)

response = client.models.generate_content(
    model = "gemini-3.1-flash-lite", contents = prompt
)

print("回答：")
print(response.text)

#回答：
#つばめちゃんの目的地の駅は、**九品仏（くほんぶつ）駅**です。

#理由は以下の通りです。

#1.  自由が丘駅から大井町方面への急行の次の停車駅は、**大岡山駅**です。
#2.  つばめちゃんは、各駅停車に乗るべきところを急行に乗ってしまったため、次の停車駅である「大岡山」で降車しました。
#3.  そこから反対方向（自由が丘方面）の電車に乗り、「一駅戻った」駅が目的地です。
#4.  大井町線で大岡山の一つ手前（自由が丘寄り）の駅は、**九品仏駅**となります。